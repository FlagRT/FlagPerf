"""FlagScale 检索训练的外部观察适配器（运行时层外挂，不改训练语义）。

在既有 torch.distributed / FSDP2 / Megatron 风格训练循环外使用：

    from flagscale_adapter import ObservationSession
    obs = ObservationSession()          # 读 FLAGPROF_TRAIN_OBSERVE；未设置则完全 no-op
    with obs:                           # attach 官方 profiler + 通信探针 + 进程内 finalize
        for step in range(steps):
            with obs.phase('data', step=step):      batch = next(loader)
            with obs.phase('forward', step=step):   loss = loss_fn(model(**batch))
            with obs.phase('backward', step=step):  loss.backward()
            with obs.phase('optimizer', step=step): opt.step(); opt.zero_grad()
            with obs.phase('step', step=step):      pass

要求：训练脚本使用标准 torch.distributed（默认进程组）；多卡时适配器会在 gloo
control group 上安装集合通信探针，fsdp2 funcol 与 p2p 入口均被覆盖。
输出：<FLAGPROF_TRAIN_OBSERVE>/rank-N/ 下的 writer store 与官方 trace，
供 flagprof 报表（通信分列 / 按 rank 归集 / 等待-带宽 / 相段占比）消费。
"""
import os
from contextlib import contextmanager, nullcontext


class ObservationSession:
    def __init__(self):
        self.enabled = bool(os.environ.get('FLAGPROF_TRAIN_OBSERVE'))
        self.handle = None
        self.run = None

    def _detect_vendor(self):
        """npu → ascend；PPU → thead；其余 NVIDIA → nvidia；显式变量优先。"""
        override = os.environ.get('FLAGPROF_TRAIN_OBSERVE_VENDOR')
        if override:
            return override
        import torch
        try:
            if torch.npu.is_available():
                return 'ascend'
        except (AttributeError, RuntimeError):
            pass
        try:
            if 'PPU' in torch.cuda.get_device_name():
                return 'thead'
            return 'nvidia'
        except (RuntimeError, AssertionError):
            return 'thead'

    def __enter__(self):
        if not self.enabled:
            return self
        import torch  # noqa: F401  (确保后端已初始化)
        import torch.distributed as dist
        from pathlib import Path
        from flagprof.runtime import attach
        from flagprof.store import create_run
        rank = int(os.environ.get('RANK', '0'))
        world = int(os.environ.get('WORLD_SIZE', '1'))
        vendor = self._detect_vendor()
        os.environ.setdefault('XPU_ENABLE_PROFILER_TRACING', '1')
        root = Path(os.environ['FLAGPROF_TRAIN_OBSERVE'])
        if vendor == 'thead' and not os.environ.get('FLAGPROF_THEAD_IDENTITY'):
            # 与训练引擎一致的零配置：身份文件缺失时由 torch 真实设备栈生成。
            from flagprof.vendors.thead.session import generate_identity_file
            identity_dir = root / ('rank-' + str(rank))
            identity_dir.mkdir(parents=True, exist_ok=True)
            identity_path = str(identity_dir / 'identity-autogenerated.json')
            generate_identity_file(identity_path, rank=rank)
            os.environ['FLAGPROF_THEAD_IDENTITY'] = identity_path
        run = create_run(root / ('rank-' + str(rank)),
                         identity=dict(diagnostic='flagscale-integration/1', vendor=vendor,
                                       preset='perf', world_size=world))
        self.handle = attach(run, vendor, preset='perf', rank=rank)
        if self.handle.state['status'] != 'running':
            raise RuntimeError('flagprof attach failed: %s'
                               % (self.handle.state.get('errors'),))
        os.environ.setdefault('FLAGPROF_GROUP_ID', run.name)
        if world > 1 and dist.is_initialized():
            control = dist.new_group(backend='gloo')
            from flagprof.probes.communication import CommunicationProbe
            probe = CommunicationProbe(self.handle.probe_manager, control)
            probe.install()
            self.handle.probe_manager.communication = probe
        self.run = run
        return self

    def phase(self, name, *, step, microstep=None):
        if not self.enabled:
            return nullcontext()
        from flagprof.training import phase as training_phase
        return training_phase(name, step=step, microstep=microstep)

    def __exit__(self, exc_type, exc, tb):
        if not self.enabled:
            return False
        ok = exc_type is None
        try:
            self.handle.close(normal=ok, returncode=0 if ok else 1)
        finally:
            if ok:
                try:
                    from flagprof.store.manifest import finalize
                    finalize(self.run)
                except BaseException as error:  # noqa: BLE001
                    print('flagprof finalize error:', type(error).__name__, error, flush=True)
        return False
